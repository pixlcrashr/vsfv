package repository

import (
	"context"
	"errors"
	"fmt"

	"github.com/google/uuid"
	"github.com/pixlcrashr/vsfv/pkg/db/model"
	"github.com/pixlcrashr/vsfv/pkg/db/model/dao"
	"github.com/theater-improrama/go-utils/optional"
	"gorm.io/gorm"
)

var ErrCommitteePaymentAccountNotFound = errors.New("committee payment account not found")

// CommitteePaymentAccountRepository provides CRUD for the
// committee_payment_accounts table.
type CommitteePaymentAccountRepository struct {
	db *gorm.DB
	q  *dao.Query
}

// NewCommitteePaymentAccountRepository creates a
// CommitteePaymentAccountRepository backed by db.
func NewCommitteePaymentAccountRepository(db *gorm.DB) *CommitteePaymentAccountRepository {
	return &CommitteePaymentAccountRepository{db: db, q: dao.Use(db)}
}

// List returns the payment accounts of a committee, oldest first, along with
// the total count.
func (r *CommitteePaymentAccountRepository) List(ctx context.Context, committeeID uuid.UUID, page, pageSize int) ([]*model.CommitteePaymentAccount, int64, error) {
	if pageSize <= 0 {
		pageSize = 20
	}
	if page <= 0 {
		page = 1
	}

	db := r.db.WithContext(ctx).Model(&model.CommitteePaymentAccount{}).
		Where("committee_id = ?", committeeID)

	var total int64
	if err := db.Count(&total).Error; err != nil {
		return nil, 0, fmt.Errorf("count committee payment accounts committee_id=%s: %w", committeeID, err)
	}

	offset := (page - 1) * pageSize
	if offset > 0 {
		db = db.Offset(offset)
	}
	db = db.Limit(pageSize)

	var ms []*model.CommitteePaymentAccount
	if err := db.Order("created_at ASC, id ASC").Find(&ms).Error; err != nil {
		return nil, 0, fmt.Errorf("list committee payment accounts committee_id=%s: %w", committeeID, err)
	}

	return ms, total, nil
}

// GetByID returns the payment account with the given ID within a committee.
func (r *CommitteePaymentAccountRepository) GetByID(ctx context.Context, committeeID, id uuid.UUID) (*model.CommitteePaymentAccount, error) {
	m, err := r.q.CommitteePaymentAccount.WithContext(ctx).
		Where(
			r.q.CommitteePaymentAccount.ID.Eq(id),
			r.q.CommitteePaymentAccount.CommitteeID.Eq(committeeID),
		).
		First()
	if err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return nil, errors.Join(ErrCommitteePaymentAccountNotFound, fmt.Errorf("id=%s committee_id=%s: %w", id, committeeID, err))
		}
		return nil, fmt.Errorf("get committee payment account id=%s committee_id=%s: %w", id, committeeID, err)
	}
	return m, nil
}

// CreateCommitteePaymentAccountParams holds the fields required to create a
// payment account.
type CreateCommitteePaymentAccountParams struct {
	CommitteeID  uuid.UUID
	Kind         model.PaymentAccountKind
	DisplayLabel string
}

// Create inserts a new payment account of a committee. The primary key (which
// doubles as the public uid referenced by submissions) is generated by the
// model's BeforeCreate hook.
func (r *CommitteePaymentAccountRepository) Create(ctx context.Context, params CreateCommitteePaymentAccountParams) (*model.CommitteePaymentAccount, error) {
	m := &model.CommitteePaymentAccount{
		CommitteeID:  params.CommitteeID,
		Kind:         params.Kind,
		DisplayLabel: params.DisplayLabel,
	}

	if err := r.db.WithContext(ctx).Create(m).Error; err != nil {
		return nil, fmt.Errorf("create committee payment account committee_id=%s: %w", params.CommitteeID, err)
	}
	return m, nil
}

// UpdateCommitteePaymentAccountParams holds the fields that can be updated
// for a payment account.
type UpdateCommitteePaymentAccountParams struct {
	Kind         optional.Optional[model.PaymentAccountKind]
	DisplayLabel optional.Optional[string]
}

// Update updates scalar fields of an existing payment account matched by its
// primary key within a committee.
func (r *CommitteePaymentAccountRepository) Update(ctx context.Context, committeeID, id uuid.UUID, params UpdateCommitteePaymentAccountParams) error {
	sets := map[string]any{}

	if params.Kind.IsSet {
		sets["kind"] = params.Kind.Value
	}
	if params.DisplayLabel.IsSet {
		sets["display_label"] = params.DisplayLabel.Value
	}

	if len(sets) == 0 {
		return nil
	}

	result := r.db.WithContext(ctx).Model(&model.CommitteePaymentAccount{}).
		Where("id = ? AND committee_id = ?", id, committeeID).
		Updates(sets)
	if result.Error != nil {
		return fmt.Errorf("update committee payment account id=%s committee_id=%s: %w", id, committeeID, result.Error)
	}
	if result.RowsAffected == 0 {
		return errors.Join(ErrCommitteePaymentAccountNotFound, fmt.Errorf("id=%s committee_id=%s: %w", id, committeeID, gorm.ErrRecordNotFound))
	}
	return nil
}

// Delete removes the payment account with the given ID within a committee.
// Submissions that reference the account keep their stored label snapshot.
func (r *CommitteePaymentAccountRepository) Delete(ctx context.Context, committeeID, id uuid.UUID) error {
	result := r.db.WithContext(ctx).
		Where("committee_id = ?", committeeID).
		Delete(&model.CommitteePaymentAccount{}, id)
	if result.Error != nil {
		return fmt.Errorf("delete committee payment account id=%s committee_id=%s: %w", id, committeeID, result.Error)
	}
	if result.RowsAffected == 0 {
		return errors.Join(ErrCommitteePaymentAccountNotFound, fmt.Errorf("id=%s committee_id=%s: %w", id, committeeID, gorm.ErrRecordNotFound))
	}
	return nil
}
